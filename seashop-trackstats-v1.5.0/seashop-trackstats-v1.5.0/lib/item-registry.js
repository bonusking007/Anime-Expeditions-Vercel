const byKey = Object.fromEntries(ITEM_REGISTRY.map(([key, display, assetId]) => [key, { key, display, assetId }]));
const byDisplay = Object.fromEntries(ITEM_REGISTRY.map(([key, display, assetId]) => [display.toLowerCase(), { key, display, assetId }]));

function resolveItem(inputName) {
  if (!inputName) return null;
  return byKey[inputName] || byDisplay[String(inputName).toLowerCase()] || null;
}

function assetThumb(assetId) {
  return assetId ? `https://www.roblox.com/asset-thumbnail/image?assetId=${assetId}&width=96&height=96&format=png` : '';
}

